#!/usr/bin/env python3
"""Create Task 8 fitness-distance correlation charts from the Go analysis."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from oeviz import (  # noqa: E402
    ACCENT,
    INK_MUTED,
    INK_SECONDARY,
    SURFACE,
    apply_theme,
    save_figure,
)

# version -> (description, JSON field prefix, y-axis wording)
VERSIONS = {
    "average_similarity": (
        "average similarity to all other local optima", "avg", "average number of"),
    "similarity_to_best_local_optimum": (
        "similarity to the best sampled local optimum", "best", "number of"),
    "similarity_to_best_method": (
        "similarity to the best prior method (ILS)", "reference", "number of"),
}
MEASURES = {
    "common_edges": "common edges",
    "common_nodes": "common selected nodes",
}


def chart_points(dataset: dict, version: str, measure: str) -> tuple[list[int], list[float]]:
    """Objective and similarity vectors with the 100%-self-similarity points removed."""
    best_index = dataset["best_local_optimum"]
    field = f"{VERSIONS[version][1]}_{measure}"
    objectives, similarities = [], []
    for i, optimum in enumerate(dataset["local_optima"]):
        if version == "similarity_to_best_local_optimum" and i == best_index:
            continue
        if version == "similarity_to_best_method" and optimum["identical_to_reference"]:
            continue
        objectives.append(optimum["objective"])
        similarities.append(optimum[field])
    return objectives, similarities


def correlation(x: list[int], y: list[float]) -> float | None:
    if len(x) < 2 or np.std(x) == 0 or np.std(y) == 0:
        return None
    return float(np.corrcoef(x, y)[0, 1])


def plot_chart(
    dataset: dict, version: str, measure: str, output: Path
) -> tuple[str, str, str, int, float | None]:
    instance = Path(dataset["instance"]).stem
    objectives, similarities = chart_points(dataset, version, measure)
    coefficient = correlation(objectives, similarities)

    apply_theme()
    fig, ax = plt.subplots(figsize=(6.3, 4.3))
    fig.subplots_adjust(left=0.13, right=0.97, bottom=0.15, top=0.82)
    ax.scatter(
        objectives,
        similarities,
        s=18,
        color=ACCENT,
        alpha=0.55,
        edgecolors=SURFACE,
        linewidths=0.35,
    )
    ax.set_xlabel("objective value (lower is better)")
    ax.set_ylabel(f"{VERSIONS[version][2]} {MEASURES[measure]}")
    ax.set_title(f"{instance}: {MEASURES[measure]}", loc="left", pad=10)
    ax.text(
        0, 1.035, VERSIONS[version][0],
        transform=ax.transAxes, fontsize=8.5, color=INK_MUTED, ha="left",
    )
    r_text = "undefined" if coefficient is None else f"{coefficient:.4f}"
    ax.text(
        0.98, 1.035, f"Pearson r = {r_text} · n = {len(objectives)}",
        transform=ax.transAxes, fontsize=8.5, color=INK_SECONDARY, ha="right",
    )
    ax.grid(axis="both", zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)

    save_figure(fig, output / f"{version}_{measure}_{instance}.png")
    return instance, version, measure, len(objectives), coefficient


def fmt(coefficient: float | None, digits: int) -> str:
    return "undefined" if coefficient is None else f"{coefficient:.{digits}f}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path, help="Task 8 JSON generated by the Go analysis")
    parser.add_argument("--out", type=Path, default=Path("report/figures_task8"))
    parser.add_argument(
        "--correlations",
        type=Path,
        default=Path("report/task8_correlations.csv"),
        help="write the Pearson coefficients table to this CSV",
    )
    args = parser.parse_args()

    data = json.loads(args.data.read_text(encoding="utf-8"))
    rows = [
        plot_chart(dataset, version, measure, args.out)
        for dataset in data
        for version in VERSIONS
        for measure in MEASURES
    ]

    args.correlations.parent.mkdir(parents=True, exist_ok=True)
    with args.correlations.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["instance", "similarity_version", "measure", "n", "pearson_r"])
        for instance, version, measure, count, coefficient in rows:
            writer.writerow([instance, version, measure, count,
                             "" if coefficient is None else f"{coefficient:.8f}"])

    print("| Instance | Similarity version | Measure | n | Pearson r |")
    print("|---|---|---|---:|---:|")
    for instance, version, measure, count, coefficient in rows:
        print(f"| {instance} | {version} | {measure} | {count} | {fmt(coefficient, 4)} |")
    print(f"\nWrote {len(rows)} charts to {args.out}")
    print(f"Correlation table written to {args.correlations}")


if __name__ == "__main__":
    main()